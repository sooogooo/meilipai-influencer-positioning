# ══ 计分仿真(scoreOf 的 Python 镜像)══════════════════════
BASE = {"REB": 40, "OWN": 26, "AD": 22, "C2C": 8, "NONE": 6}
STABLE = {"EXP|C2C","INTEL|C2C","AES|AD","IND|OWN","QUAL|NONE","IND|C2C","QUAL|C2C","IND|AD"}
random.seed(42)
drs, gaps, states = [], [], {}
for _ in range(500):
    sel = [random.choice(slot) for slot in S]
    ans = [random.randrange(len(qq["o"])) for qq in sel]
    t = {k: 0.0 for k in T5}; m = "NONE"; v = {"r":0,"d":0,"p":0,"a":0,"b":0,"c":0,"e":0}
    for k, qq in zip(ans, sel):
        for key, val in qq["o"][k][1].items():
            if key == "m": m = val
            elif key in v: v[key] = val
            else: t[key] += val
    rank = sorted(T5, key=lambda x: -t[x])
    gap = t[rank[0]] - t[rank[1]]
    dr = min(100, round(BASE[m] + v["r"]*4 + v["d"]*5 + v["p"]*4 + v["a"]*5 + v["b"]*4 + v["c"]*3 + v["e"]*4))
    cell = rank[0] + "|" + m
    st = "高危" if m == "REB" else ("稳定" if cell in STABLE else "过渡态")
    drs.append(dr); gaps.append(gap); states[st] = states.get(st, 0) + 1
    assert 0 <= dr <= 100
print(f"500 次随机抽样仿真: 贴现率 {min(drs)}-{max(drs)} (均值 {sum(drs)/500:.1f}), "
      f"信任差 {min(gaps)}-{max(gaps)}, 判定分布 {states}")

