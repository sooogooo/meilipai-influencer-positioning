def js_q(qq):
    opts = ",".join(f"[{json.dumps(txt, ensure_ascii=False)},{js_w(w)}]" for txt, w in qq["o"])
    n = json.dumps(qq["n"], ensure_ascii=False)
    return f'{{s:{json.dumps(qq["s"], ensure_ascii=False)},t:{json.dumps(qq["t"], ensure_ascii=False)},n:{n},o:[{opts}]}}'

slots_js = ",\n".join("  [\n" + ",\n".join("   " + js_q(qq) for qq in slot) + "\n  ]" for slot in S)
open("/tmp/qbank.js", "w").write("QB = [\n" + slots_js + "\n  ];\n")
